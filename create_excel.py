import pandas as pd

# Excelの列名（全35項目：日付、対戦相手、選手名 ＋ 成績32項目）
cols = [
    '日付', '対戦相手', '選手名', '試合', '登板', 'イニング', 'アウト', '犠アウト', 'ゴロo', 'フライo', 
    '奪三振右', '奪三振左', 'その他o', '打席右', '打席左', '打数右', '打数左', 
    '被安打右', '被安打左', '被本塁打', '与四球右', '与四球左', '与死球右', 
    '与死球左', '暴投', 'ボーク', '失点', '自責点', '勝ち', '負け', 'セーブ', 
    'ホールド', '先発', '初球S', '投球数'
]

# データの中身（足りない空欄はプログラムが自動で補います！）
data = [
    ['6月13日', '岐阜聖徳学園大学', '佐藤', 'OP戦', 1, 2, 6, '', 2, '', 2, 1, '', 5, '', 5, '', 1, '', '', '', '', '', '', '', '', '', '', '', '', '', '', 3, 36],
    ['7月19日', '日本大学国際関係学部', '佐藤', 'OP戦', 1, 3, 9, '', 2, 6, '', '', 1, 3, 12, 3, 11, '', 6, '', '', 1, '', '', '', '', '', '', '', '', 1, 9, 54]
]

# 自動で列数を合わせる処理
padded_data = [row + [''] * (len(cols) - len(row)) for row in data]
df = pd.DataFrame(padded_data, columns=cols)

# Excelファイルとして保存
file_name = 'テーブル形式_投手データ取込用.xlsx'
df.to_excel(file_name, index=False)

print(f"{file_name} を無事に作成しました！")